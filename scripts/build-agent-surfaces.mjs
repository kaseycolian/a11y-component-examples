/**
 * Read a source file, strip a UTF-8 BOM (JSON.parse rejects one), and refuse
 * mojibake.
 *
 * `â€` is the signature of UTF-8 bytes read back as Latin-1 and re-encoded --
 * an em-dash becomes `â€"`. PowerShell 5.1's `Set-Content -Encoding utf8` does
 * this to any file it round-trips, which is easy to do by accident on Windows
 * and produces prose that looks fine in a diff summary and wrong on the page.
 * Every one of these files is prose or JSON destined for a generated surface,
 * so catching it here is the last point where it is still cheap.
 */
async function readSource(path) {
  const text = (await readFile(path, 'utf8')).replace(/^﻿/, '');
  if (text.includes('â€')) {
    throw new Error(
      `${path} contains mojibake ("â€") -- it was re-encoded by something that read UTF-8 as ` +
        `Latin-1. Restore it with \`git checkout --\` rather than retyping the characters.`,
    );
  }
  return text;
}

/**
 * The `skill-*` two render into SKILL.md alone, which is why they can be prose
 * of any length while the rest are under pressure.
 */
const SLOTS = ['title', 'intro', 'rules', 'copying', 'outro', 'skill-description', 'skill-audience'];

/**
 * Split the preamble on its `<!-- slot: name -->` markers.
 *
 * The split is on the markers only, never on the prose -- the reason this repo
 * rejected docs/component-specs.md as a machine source is that parsing prose is
 * confidently wrong. Anything before the first marker is prose for whoever is
 * editing the file, and is dropped.
 */
async function readSlots() {
  const text = await readSource(PREAMBLE);
  const parts = text.split(/^<!-- slot: ([a-z-]+) -->$/gm);
  const found = new Map();

  for (let i = 1; i < parts.length; i += 2) {
    found.set(parts[i], parts[i + 1].trim());
  }

  const unknown = [...found.keys()].filter((name) => !SLOTS.includes(name));
  const missing = SLOTS.filter((name) => !found.has(name));
  if (unknown.length || missing.length) {
    const problems = [
      unknown.length && `unknown slot(s): ${unknown.join(', ')}`,
      missing.length && `missing slot(s): ${missing.join(', ')}`,
    ].filter(Boolean);
    throw new Error(`docs/agents/preamble.md -- ${problems.join('; ')}`);
  }
  return Object.fromEntries(SLOTS.map((name) => [name, found.get(name)]));
}

/**
 * Read one of the docs/agents/*.src.md sources.
 *
 *   <!-- lede -->              the file's opening paragraphs
 *   <!-- group: Title -->      a section
 *   <!-- item: Title -->       an entry
 *   <!-- item: Title · 4.1.2 4.1.3 -->
 *
 * Same rule as readSlots(): the split is on the markers and never on the prose,
 * so a body is passed through byte for byte and can contain anything markdown
 * allows -- a fenced block, a second paragraph, a nested list. Everything above
 * the first marker is a note for whoever edits the file and is dropped, which is
 * how each source explains its own format at the top.
 *
 * The success criteria after ` · ` are optional by design. Several entries are
 * mechanisms rather than failures, and a made-up tag on one of those would make
 * every real tag less trustworthy.
 */
async function readEntries(name) {
  const path = resolve(AGENT_DOCS, name);
  const text = await readSource(path);
  const bad = (msg) => {
    throw new Error(`docs/agents/${name} -- ${msg}`);
  };

  // A misspelled kind is otherwise silently demoted to prose, and surfaces
  // several checks later as "this group has prose of its own" -- a true error
  // pointing at the wrong line. Same treatment as an unknown slot.
  const KINDS = ['lede', 'group', 'item'];
  const unknown = [...text.matchAll(/^<!--[ \t]*([a-z][a-z-]*)[ \t]*(?::[^>]*)?-->[ \t]*$/gm)]
    .map((match) => match[1])
    .filter((kind) => !KINDS.includes(kind));
  if (unknown.length) bad(`unknown marker(s): ${[...new Set(unknown)].join(', ')}. Have: ${KINDS.join(', ')}`);

  const parts = text.split(/^<!-- (lede|group|item)(?::[ \t]*(.*?))?[ \t]*-->[ \t]*$/gm);
  let lede = null;
  const groups = [];

  for (let i = 1; i < parts.length; i += 3) {
    const kind = parts[i];
    const payload = (parts[i + 1] ?? '').trim();
    const body = parts[i + 2].trim();

    if (kind === 'lede') {
      if (payload) bad('the lede marker takes no title');
      if (lede) bad('more than one lede');
      if (!body) bad('the lede is empty');
      lede = body;
      continue;
    }
    if (kind === 'group') {
      if (!payload) bad('a group marker needs a title');
      // Prose directly under a group marker has nowhere to render, so it would
      // silently disappear. Put it in the first item instead.
      if (body) bad(`group "${payload}" has prose of its own; only items carry prose`);
      groups.push({ title: payload, items: [] });
      continue;
    }

    if (!groups.length) bad(`item "${payload}" comes before any group`);
    const [title, sc] = payload.split(' · ');
    if (!title?.trim()) bad('an item marker needs a title');
    if (!body) bad(`item "${title}" has no body`);

    // `4.12` for `4.1.2` renders as a plausible-looking tag and is wrong
    // forever, so the shape is checked rather than trusted.
    const wcag = sc ? sc.trim().split(/\s+/) : [];
    const malformed = wcag.filter((ref) => !/^\d+\.\d+\.\d+$/.test(ref));
    if (malformed.length) bad(`item "${title}" has success criteria that are not N.N.N: ${malformed.join(', ')}`);

    groups.at(-1).items.push({ title: title.trim(), wcag, body });
  }

  if (!lede) bad('no <!-- lede --> marker');
  if (!groups.length) bad('no <!-- group: … --> markers');
  const empty = groups.filter((g) => !g.items.length).map((g) => g.title);
  if (empty.length) bad(`group(s) with no items: ${empty.join(', ')}`);

  return { lede, groups };
}

/**
 * Bold lead, WCAG tags, then the body verbatim.
 *
 * Headings per entry were the other option and cost a structural line each for
 * navigation an agent reading a single 12 KB file does not need. Same call as
 * the Tier 2 files, which use `**States:**` rather than a heading for anything
 * short.
 */
function renderProse(surface, { lede, groups }) {
  const out = [`<!-- ${DO_NOT_EDIT} -->`, '', `# ${surface.title}`, '', lede];

  for (const group of groups) {
    out.push('', `## ${group.title}`);
    for (const item of group.items) {
      const tags = item.wcag.length ? ` · WCAG ${item.wcag.join(' ')}` : '';
      out.push('', `**${item.title}**${tags}`, '', item.body);
    }
  }
  return `${out.join('\n')}\n`;
}

/**
 * The shape of a `contract` block. Only `useWhen` and `failureModes` are
 * required -- a CSS-only component has no keyboard map and no API, and a stub
 * with empty sections would cost an agent a fetch to learn nothing.
 */
const CONTRACT_FIELDS = ['useWhen', 'aria', 'keyboard', 'states', 'failureModes', 'api', 'seeAlso'];

/**
 * Check the shape of a contract, and nothing about the world.
 *
 * A contract is rendered straight into a Tier 2 file, so a malformed one ships
 * as broken markdown instead of as an error -- and the budget check would then
 * be measuring garbage. The checks that matter more, that the ARIA is really in
 * the markup and the keys are really tested, need a browser and a running page;
 * they live in tests/shared/agent-surfaces.spec.mjs.
 *
 * Deliberately no `pattern` field: meta.json already has `apg` with that URL,
 * and a second place to put it is a second place for it to be wrong.
 */
function validateContract(slug, c) {
  const bad = (msg) => {
    throw new Error(`${slug}/meta.json "contract" -- ${msg}`);
  };
  const strings = (value, field) => {
    if (!Array.isArray(value) || !value.length) bad(`${field} must be a non-empty array`);
    if (value.some((s) => typeof s !== 'string' || !s.trim())) {
      bad(`${field} must hold non-empty strings`);
    }
  };

  const unknown = Object.keys(c).filter((key) => !CONTRACT_FIELDS.includes(key));
  if (unknown.length) bad(`unknown field(s): ${unknown.join(', ')}. Have: ${CONTRACT_FIELDS.join(', ')}`);

  if (typeof c.useWhen !== 'string' || !c.useWhen.trim()) bad('useWhen is required');
  // It is also the component's row in agents/index.md, where the whole roster
  // shares one budget, so a paragraph here is spent out of everyone else's line.
  if (c.useWhen.includes('\n')) bad('useWhen is one line -- it is also the index row');

  // The field an author is most tempted to skip and the one worth the most.
  // Asserting only that it exists is weak; it is still the check that stops the
  // block from becoming a restatement of the markup.
  strings(c.failureModes, 'failureModes');

  if (c.aria !== undefined) {
    if (!c.aria || typeof c.aria !== 'object' || Array.isArray(c.aria)) {
      bad('aria must be an object of part -> attributes');
    }
    for (const [part, attrs] of Object.entries(c.aria)) strings(attrs, `aria["${part}"]`);
  }
  if (c.keyboard !== undefined) {
    if (!Array.isArray(c.keyboard) || !c.keyboard.length) bad('keyboard must be a non-empty array');
    for (const pair of c.keyboard) {
      if (!Array.isArray(pair) || pair.length !== 2) bad('keyboard entries are [key, effect] pairs');
      strings(pair, 'a keyboard entry');
    }
  }
  for (const field of ['states', 'api', 'seeAlso']) {
    if (c[field] !== undefined) strings(c[field], field);
  }
}

const GROUP_INDEX = new Map(GROUPS.map((g, i) => [g.id, i]));

/**
 * Read every component's meta.json.
 *
 * Deliberately not via src/site/lib/registry.mjs: that module globs with
 * `import.meta.glob`, which only exists inside Vite, so plain Node cannot load
 * it. Both read the same meta.json files and both validate `group` against the
 * same list, which is why groups.mjs is its own module.
 */
async function readComponents() {
  const slugs = (await readdir(COMPONENTS_DIR, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);

  const components = [];
  for (const slug of slugs) {
    const file = resolve(COMPONENTS_DIR, slug, 'meta.json');
    if (!existsSync(file)) continue;

    let meta;
    try {
      meta = JSON.parse(await readSource(file));
    } catch (err) {
      throw new Error(`${slug}/meta.json is not valid JSON: ${err.message}`);
    }
    if (!GROUP_INDEX.has(meta.group)) {
      throw new Error(
        `${slug}/meta.json has group "${meta.group}", which is not in groups.mjs. ` +
          `Valid: ${GROUPS.map((g) => g.id).join(', ')}`,
      );
    }

    if (meta.contract) validateContract(slug, meta.contract);

    components.push({
      slug: meta.slug ?? slug,
      name: meta.name ?? slug,
      group: meta.group,
      order: meta.order ?? 100,
      tags: meta.tags ?? [],
      apg: meta.apg ?? null,
      wcag: meta.wcag ?? [],
      status: meta.status ?? 'stable',
      files: meta.files ?? ['html', 'css', 'js'],
      contract: meta.contract ?? null,
    });
  }

  // Write mode clears agents/ before rendering, so an empty roster would quietly
  // replace every surface with a shell. That only happens in a broken tree, and
  // failing is the useful response to one.
  if (components.length === 0) {
    throw new Error(`no meta.json found under ${COMPONENTS_DIR} -- refusing to write empty surfaces`);
  }

  // Same ordering as the registry, so the agent index and the human nav list
  // the library in the same sequence.
  return components.sort(
    (a, b) =>
      GROUP_INDEX.get(a.group) - GROUP_INDEX.get(b.group) ||
      a.order - b.order ||
      a.name.localeCompare(b.name),
  );
}

async function buildManifest() {
  const astro = await readSource(resolve(root, 'astro.config.mjs'));

  // The published origin and base path are declared once, in astro.config.mjs.
  // Reading them back beats a second copy here that could disagree about where
  // the site actually is -- every URL in llms.txt depends on getting it right.
  const site = astro.match(/^\s*site:\s*'([^']+)'/m)?.[1];
  const base = astro.match(/^\s*base:\s*'([^']+)'/m)?.[1];
  if (!site || !base) {
    throw new Error('astro.config.mjs -- could not read `site` and `base`');
  }

  const components = await readComponents();
  return {
    baseUrl: `${site}${base}/`,
    slots: await readSlots(),
    prose: await Promise.all(
      PROSE_SURFACES.map(async (surface) => ({ ...surface, ...(await readEntries(surface.src)) })),
    ),
    components,
    groups: GROUPS.map((group) => ({
      ...group,
      components: components.filter((c) => c.group === group.id),
    })).filter((group) => group.components.length > 0),
  };
}

