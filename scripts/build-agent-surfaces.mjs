/**
 * Build every agent-facing surface from one manifest.
 *
 *   node scripts/build-agent-surfaces.mjs           write
 *   node scripts/build-agent-surfaces.mjs --check   re-render and diff, exit 1 on drift
 *
 * There are several surfaces because agents arrive by different doors: a repo
 * checkout reads AGENTS.md, an HTTP fetcher reads llms.txt, Claude Code loads a
 * skill. They must never disagree, so they are not separate documents -- they
 * are renderings of one in-memory manifest, and no output file is ever half
 * hand-written and half generated. That single property is what makes --check
 * possible: it re-renders into memory and compares byte for byte.
 *
 * Sources of truth, and the only places to edit:
 *
 *   src/library/components/<slug>/meta.json   the roster, and each contract
 *   src/site/lib/groups.mjs                   group order, names, blurbs
 *   docs/agents/preamble.md                   the Tier 0 prose, in slots
 *   docs/agents/*.src.md                      the cross-cutting surfaces
 *   astro.config.mjs  site + base             where the served copies live
 *
 * Everything under agents/ and AGENTS.md itself is output. Editing one by hand
 * fails `npm run check:agents`, which runs in CI -- that is the whole mechanism.
 *
 * Two rules the renderers here have to keep (see CLAUDE.md):
 *   - Never count the components. No totals, in prose or in a heading.
 *   - Nothing non-deterministic. No timestamps, no build ids, no file mtimes.
 *     A generator whose output changes on its own makes --check a coin flip.
 *
 * See docs/agent-layer.md for why the layer is shaped this way.
 */
import { readFile, writeFile, mkdir, rm, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, posix } from 'node:path';

import { GROUPS } from '../src/site/lib/groups.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const COMPONENTS_DIR = resolve(root, 'src/library/components');
const AGENT_DOCS = resolve(root, 'docs/agents');
const PREAMBLE = resolve(AGENT_DOCS, 'preamble.md');

// Names the command and where the sources live, so someone who opens a
// generated file cold knows where to go. It lands in every surface, including
// the ones under a byte budget, which is why it names the folder rather than
// listing the six files in it.
const DO_NOT_EDIT = 'generated by npm run agents -- edit docs/agents/ or a meta.json';

/**
 * The Claude Code skill: Tier 0 for an agent arriving through Claude Code
 * rather than through a checkout or an HTTP fetch.
 *
 * `SKILL_NAME` is both the frontmatter `name` and the folder name, derived once
 * because Claude Code will not load a skill whose two disagree -- and it fails
 * by never triggering, which looks exactly like a description that did not
 * match.
 *
 * The description has a length ceiling because it is always in context, unlike
 * the body, which is read only once the skill triggers. Over the limit it is
 * rejected or truncated, so a slot that grew past it has to fail here.
 */
const SKILLS_DIR = '.claude/skills';
const SKILL_NAME = 'a11y-library';
export const SKILL_OUT = `${SKILLS_DIR}/${SKILL_NAME}/SKILL.md`;
const SKILL_DESCRIPTION_MAX = 1_024;

/**
 * Hard byte budgets, from docs/agent-layer.md. Exceeding one is a build
 * failure rather than a warning: the budgets are the product. An agent that
 * spends 4 KB learning where things are has less context left for the code it
 * came here to write, and prose grows by itself unless something says no.
 *
 * The skill gets its own rather than borrowing Tier 0's 2.5 KB, which was set
 * for a file with no frontmatter. Its *body* is the leanest of the three -- it
 * drops `copying` and one intro paragraph -- but roughly 600 bytes of it is a
 * description whose entire job is keyword coverage, and cutting that is cutting
 * the routing. 3 KB is the measured size rounded up, which leaves room for about
 * two more read-path rows: the same rule as TIER_2_BUDGET.
 */
const BUDGETS = {
  'AGENTS.md': 2_560,
  'agents/llms.txt': 2_560,
  'agents/index.md': 3_584,
  [SKILL_OUT]: 3_072,
};

/**
 * Tier 2 files are per-component, so the budget is per file. Asserted here and
 * in the spec.
 *
 * The plan said 800, from the 626-byte median of a docs/component-specs.md
 * entry. That measured the wrong thing: an entry is prose bullets only, while a
 * rendered contract also carries ~250 bytes of frame (the do-not-edit header,
 * the folder line, the WCAG and APG references) plus a keyboard map and a
 * failure-mode list, neither of which a spec entry had. Written out, the roster
 * measured 0.8 KB to 1.5 KB, so 800 would have been met by deleting
 * `failureModes` -- the one field worth the most. This is the measured maximum
 * rounded up, which leaves the richest component room for about two more entries
 * and still makes a Tier 2 read cost roughly 450 tokens.
 */
export const TIER_2_BUDGET = 1_800;

/**
 * The cross-cutting surfaces. One rendered file per hand-written source under
 * docs/agents/, all four through the same parser and the same renderer.
 *
 * They are Tier 4: an agent reaches them because a component file surprised it,
 * or before writing CSS in this style for the first time -- never on the way to
 * finding a component. So the budgets are per file and generous, and the read
 * path prints all four as one grouped row. Four rows would cost Tier 0 more
 * than routing between them is worth, and the file names already say which is
 * which.
 *
 * The order is reading order for someone who will read more than one. Each
 * budget is the measured size plus room for two or three more entries -- the
 * same rule as TIER_2_BUDGET, and the reason pitfalls gets 16 KB rather than the
 * 15 KB its 14.7 KB rounds up to: one more entry would have failed the build.
 */
export const PROSE_SURFACES = [
  { src: 'pitfalls.src.md', out: 'agents/pitfalls.md', title: 'Pitfalls', budget: 16_384 },
  {
    src: 'conventions.src.md',
    out: 'agents/conventions.md',
    title: 'What a copied component assumes',
    budget: 7_168,
  },
  { src: 'verify.src.md', out: 'agents/verify.md', title: 'Verifying the result', budget: 8_192 },
  { src: 'testing.src.md', out: 'agents/testing.md', title: 'Testing traps', budget: 12_288 },
];

