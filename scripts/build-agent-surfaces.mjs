/**
 * The read path, declared once. Both Tier 0 renderings walk this, so they can
 * never advertise a different set of files, and a `file` row is only listed
 * when it was actually rendered -- which is how phase 2 and phase 3 pick up
 * their rows with no edit here.
 */
function readPath(manifest, rendered) {
  const hasTier2 = manifest.components.some((c) => c.contract);
  const rows = [
    {
      tier: 1,
      kind: 'file',
      path: 'agents/index.md',
      // Not "stop reading this file" -- the note is rendered inside AGENTS.md
      // and llms.txt, where "this file" reads as the wrong one.
      note: 'The roster. Find your component, then stop.',
    },
    {
      tier: 1,
      kind: 'file',
      path: 'agents/index.json',
      note: 'Every field, for filtering by tag or SC.',
    },
    hasTier2 && {
      tier: 2,
      kind: 'pattern',
      path: 'agents/components/<slug>.md',
      size: `≤ ${(TIER_2_BUDGET / 1024).toFixed(1)} KB`,
      note: 'The contract: roles, attributes, keys, states, what goes wrong, the JS API.',
    },
    {
      tier: 3,
      kind: 'pattern',
      path: 'library/components/<slug>/component.{html,css,js}',
      size: 'varies',
      note: 'The code. Copy from here.',
    },
    {
      tier: 4,
      kind: 'pattern',
      path: 'library/components/<slug>/{docs.md,meta.json}',
      size: 'varies',
      note: 'Why it is built that way. Read when the code surprises you.',
    },
    // One row for all four, not four rows: the file names say which is which, so
    // separate rows would spend Tier 0's budget on routing between things a
    // reader can already tell apart. The size quoted is the largest single file,
    // because one fetch is what it costs.
    PROSE_SURFACES.every((s) => rendered.has(s.out)) && {
      tier: 4,
      kind: 'pattern',
      path: `agents/{${PROSE_SURFACES.map((s) => s.out.match(/([^/]+)\.md$/)[1]).join(',')}}.md`,
      size: `≤ ${kb(Math.max(...PROSE_SURFACES.map((s) => bytes(rendered.get(s.out)))))}`,
      note: 'The traps that cost a real failure, and what a copied component assumes about your page.',
    },
  ].filter(Boolean);

  return rows
    .filter((row) => row.kind !== 'file' || rendered.has(row.path))
    .map((row) => ({ ...row, size: row.size ?? kb(bytes(rendered.get(row.path))) }));
}

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;

/**
 * A tag on a fifth of the library cannot route -- it costs a line and narrows
 * nothing. Expressed as a share rather than a count so it still means the same
 * thing as the roster grows. The index names the ones it dropped, because a
 * *missing* `forced-colors` would otherwise read as "this one does not handle
 * it" when every component does.
 */
const UNROUTABLE_TAG_SHARE = 0.2;

/**
 * Keywords worth spending an index line on, for a component with no `useWhen`
 * yet. A one-line "what it is for" routes better than three keywords do, so a
 * row shows tags only as the fallback.
 *
 * Dropped: tags that restate the slug (the row already leads with it), and tags
 * common enough to match everything. `name` is dropped from the row entirely for
 * the same reason -- it is the title-cased slug in every component in the
 * library, so it carries no information the slug does not.
 */
function routingTags(component, df, ceiling) {
  const own = component.slug.split('-');
  return component.tags.filter(
    (tag) => !own.includes(tag) && tag !== component.slug && df.get(tag) <= ceiling,
  );
}

function renderIndex(manifest) {
  const df = new Map();
  for (const c of manifest.components) {
    for (const tag of c.tags) df.set(tag, (df.get(tag) ?? 0) + 1);
  }
  const ceiling = manifest.components.length * UNROUTABLE_TAG_SHARE;

  // A row carries its `useWhen` or its keywords, never both: the sentence
  // already contains the words, so printing them again spends the roster's one
  // shared budget on a duplicate.
  const rows = [];
  let anyTags = false;
  for (const group of manifest.groups) {
    rows.push('', `## ${group.name}`, '');
    for (const c of group.components) {
      const use = c.contract?.useWhen;
      const tags = use ? [] : routingTags(c, df, ceiling);
      if (tags.length) anyTags = true;
      rows.push(
        [
          `- **${c.slug}**`,
          use ? ` — ${use}` : '',
          tags.length ? ` · ${tags.join(', ')}` : '',
          c.status !== 'stable' ? ` · **${c.status}**` : '',
        ].join(''),
      );
    }
  }

  // Where a row points depends on whether Tier 2 exists yet. Saying "read the
  // slug's own file" before any contract block is written would send an agent
  // to a 404.
  const next = manifest.components.some((c) => c.contract)
    ? 'Pick one, then read `agents/components/<slug>.md` — not this file twice.'
    : 'Pick one, then read `library/components/<slug>/component.html` and its siblings.';

  const out = [`<!-- ${DO_NOT_EDIT} -->`, '', '# Component index', '', next];

  if (anyTags) {
    const common = [...df]
      .filter(([, n]) => n > ceiling)
      .map(([tag]) => tag)
      .sort();
    out.push(
      '',
      'A row with no sentence of its own falls back to keywords. The ones true of most of the library',
      `are left off: ${common.map((t) => `\`${t}\``).join(', ')}. Assume them.`,
    );
  }

  return [...out, ...rows, ''].join('\n');
}

/**
 * Pretty-printed JSON puts every tag on its own line, which turned this file
 * into 20.8 KB of mostly indentation -- six times the markdown index it is
 * supposed to be an alternative to. Objects stay expanded because they are what
 * a person skims; arrays of short scalars collapse onto one line.
 *
 * The pattern only matches arrays whose every element is a quote-free,
 * newline-free string, so a prose value can never be caught by it, and the
 * output is valid JSON either way.
 */
const compactScalarArrays = (json) =>
  json.replace(/\[\n\s+("[^"\n]*"(?:,\n\s+"[^"\n]*")*)\n\s+\]/g, (_, items) =>
    `[${items.replace(/,\n\s+/g, ', ')}]`,
  );

function renderIndexJson(manifest) {
  const body = {
    _generated: DO_NOT_EDIT,
    baseUrl: manifest.baseUrl,
    // Templates rather than 33 expanded path lists: the shape is the same for
    // every component and an agent can fill in a slug.
    paths: {
      code: 'library/components/{slug}/component.{html|css|js}',
      docs: 'library/components/{slug}/docs.md',
      meta: 'library/components/{slug}/meta.json',
      contract: 'agents/components/{slug}.md',
    },
    groups: manifest.groups.map(({ id, name, summary }) => ({ id, name, summary })),
    components: manifest.components.map((c) => ({
      slug: c.slug,
      name: c.name,
      group: c.group,
      ...(c.contract?.useWhen ? { useWhen: c.contract.useWhen } : {}),
      tags: c.tags,
      wcag: c.wcag,
      apg: c.apg,
      files: c.files,
      status: c.status,
      hasContract: Boolean(c.contract),
    })),
  };
  return `${compactScalarArrays(JSON.stringify(body, null, 2))}\n`;
}

/** Two surfaces print the read path as a table, so they share the rendering. */
const readPathTable = (manifest, rendered) =>
  [
    '| Tier | Read | Size | For |',
    '| --- | --- | --- | --- |',
    ...readPath(manifest, rendered).map(
      (row) => `| ${row.tier} | \`${row.path}\` | ${row.size} | ${row.note} |`,
    ),
  ].join('\n');

function renderAgentsMd(manifest, rendered) {
  const { title, intro, rules, copying, outro } = manifest.slots;

  return `<!-- ${DO_NOT_EDIT} -->

# ${title}

${intro}

## Read in this order

Repo-relative. Over HTTP the same files sit under \`${manifest.baseUrl}\`, where \`llms.txt\` is this file.

${readPathTable(manifest, rendered)}

## Rules

${rules}

## What a copied component needs

${copying}

${outro}
`;
}

/**
 * llms.txt follows the llmstxt.org shape -- H1, blockquote, then link sections
 * -- because that is what a fetcher expects to find at a site root. Same slots
 * as AGENTS.md, absolute URLs instead of repo paths.
 */
function renderLlmsTxt(manifest, rendered) {
  const { title, intro, rules, copying, outro } = manifest.slots;
  const [lede, ...rest] = intro.split('\n\n');

  // Only the fetchable files get a real link; the per-slug patterns stay as
  // relative paths against the base stated once above them. Thirty-odd
  // characters of origin on every row is a third of Tier 0's budget spent
  // repeating itself.
  const links = readPath(manifest, rendered)
    .map((row) =>
      row.kind === 'file'
        ? `- [${row.path}](${manifest.baseUrl}${row.path}) — tier ${row.tier}, ${row.size}. ${row.note}`
        : `- \`${row.path}\` — tier ${row.tier}, ${row.size}. ${row.note}`,
    )
    .join('\n');

  return `<!-- ${DO_NOT_EDIT} -->

# ${title}

> ${lede.replace(/\n/g, ' ')}

${rest.join('\n\n')}

## Read in this order

Tier 0 is this file. Relative paths resolve against it; a \`<slug>\` comes from the index.

${links}

## Rules

${rules}

## What a copied component needs

${copying}

${outro}
`;
}

/**
 * A YAML single-quoted scalar -- the one form that needs no thought about the
 * content. Everything inside is literal and only `'` is escaped, by doubling it.
 * Unquoted, YAML would read the description's first colon as a key.
 */
const yamlString = (text) => `'${text.replace(/'/g, "''")}'`;

/**
 * The Claude Code skill. The same slots as the other two Tier 0 renderings, in a
 * third frame rather than as a fourth document -- so it cannot disagree with
 * them about the read path or the rules.
 *
 * Deliberately shorter than either. `copying` is left out because the Tier 4 row
 * reaches the same reasoning at greater length, and what remains is the part
 * that routes. It adds no read-path row of its own: an agent reading this is
 * already at Tier 0.
 *
 * Frontmatter comes first, and the do-not-edit marker second. That inverts the
 * order every other surface uses, because a file that does not open with `---`
 * has no frontmatter at all as far as the skill loader is concerned, and a skill
 * with no `description` never triggers.
 */
function renderSkill(manifest, rendered) {
  const { title, intro, rules, outro } = manifest.slots;
  const [lede] = intro.split('\n\n');

  const description = manifest.slots['skill-description'].replace(/\s+/g, ' ').trim();
  if (description.length > SKILL_DESCRIPTION_MAX) {
    throw new Error(
      `docs/agents/preamble.md -- the skill-description slot renders to ${description.length} ` +
        `characters, over the ${SKILL_DESCRIPTION_MAX} Claude Code allows. It is always in context, ` +
        `so cut it rather than raising the limit.`,
    );
  }

  return `---
name: ${SKILL_NAME}
description: ${yamlString(description)}
---

<!-- ${DO_NOT_EDIT} -->

# ${title}

${lede}

${manifest.slots['skill-audience']}

## Read in this order

Repo-relative in a checkout of this library. Anywhere else the same paths resolve under \`${manifest.baseUrl}\`.

${readPathTable(manifest, rendered)}

## Rules

${rules}

${outro}
`;
}

/**
 * Tier 2: one file per component, from its contract block. Components without
 * one are skipped rather than given a stub, so the read path never points an
 * agent at a file that would waste the fetch. Phase 2 fills these in.
 */
function renderComponent(component, manifest) {
  const c = component.contract;
  const out = [
    `<!-- ${DO_NOT_EDIT} -->`,
    '',
    `# ${component.name}`,
    '',
    c.useWhen,
    '',
    // One line for the folder rather than two: the path was being spent twice,
    // once to point at the code and again to point at docs.md beside it.
    `In \`library/components/${component.slug}/\` — copy ` +
      `\`component.{${component.files.join(',')}}\`, read \`docs.md\` for why.`,
  ];

  if (c.aria) {
    out.push('', '## ARIA', '');
    for (const [part, attrs] of Object.entries(c.aria)) {
      out.push(`- **${part}** — \`${attrs.join('\` \`')}\``);
    }
  }
  if (c.keyboard?.length) {
    out.push('', '## Keyboard', '');
    for (const [key, effect] of c.keyboard) out.push(`- \`${key}\` — ${effect}`);
  }
  if (c.states?.length) out.push('', `**States:** ${c.states.join(', ')}`);
  if (c.failureModes?.length) {
    out.push('', '## Goes wrong when', '');
    for (const mode of c.failureModes) out.push(`- ${mode}`);
  }
  // Eight components register more than one factory, so this is a list. The
  // demo-page wiring some of them also register is deliberately not here --
  // those files say to delete it when you copy.
  if (c.api?.length === 1) {
    out.push('', `**API:** \`${c.api[0]}\``);
  } else if (c.api?.length) {
    out.push('', '## API', '');
    for (const signature of c.api) out.push(`- \`${signature}\``);
  }

  const refs = [
    component.wcag.length && `WCAG ${component.wcag.join(' ')}`,
    component.apg && `[APG](${component.apg})`,
    c.seeAlso?.length && `see also ${c.seeAlso.map((s) => `\`${s}\``).join(', ')}`,
  ].filter(Boolean);
  if (refs.length) out.push('', refs.join(' · '));
  out.push('');

  return out.join('\n');
}

