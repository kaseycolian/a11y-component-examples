/**
 * Build every agent-facing surface from one manifest.
 *
 *   node scripts/build-agent-surfaces.mjs           write
 *   node scripts/build-agent-surfaces.mjs --check   re-render and diff, exit 1 on drift
 *
 * There are several surfaces because agents arrive by different doors: a repo
 * checkout reads AGENTS.md, an HTTP fetcher reads llms.txt, Claude Code loads a
 * skill. They must never disagree, so they are not separate documents -- they
 * are renderings of one in-memory manifest, and no output file is ever half
 * hand-written and half generated. That single property is what makes --check
 * possible: it re-renders into memory and compares byte for byte.
 *
 * Sources of truth, and the only places to edit:
 *
 *   src/library/components/<slug>/meta.json   the roster, and each contract
 *   src/site/lib/groups.mjs                   group order, names, blurbs
 *   docs/agents/preamble.md                   the Tier 0 prose, in slots
 *   astro.config.mjs  site + base             where the served copies live
 *
 * Everything under agents/ and AGENTS.md itself is output. Editing one by hand
 * fails `npm run check:agents`, which runs in CI -- that is the whole mechanism.
 *
 * Two rules the renderers here have to keep (see CLAUDE.md):
 *   - Never count the components. No totals, in prose or in a heading.
 *   - Nothing non-deterministic. No timestamps, no build ids, no file mtimes.
 *     A generator whose output changes on its own makes --check a coin flip.
 *
 * See docs/agent-layer.md for why the layer is shaped this way.
 */
import { readFile, writeFile, mkdir, rm, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, posix } from 'node:path';

import { GROUPS } from '../src/site/lib/groups.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const COMPONENTS_DIR = resolve(root, 'src/library/components');
const PREAMBLE = resolve(root, 'docs/agents/preamble.md');

// Names the command and both hand-written sources, so someone who opens a
// generated file cold knows where to go. It lands in every surface, including
// the two under a byte budget, which is why it is this short.
const DO_NOT_EDIT = 'generated by npm run agents -- edit docs/agents/preamble.md or a meta.json';

/**
 * Hard byte budgets, from docs/agent-layer.md. Exceeding one is a build
 * failure rather than a warning: the budgets are the product. An agent that
 * spends 4 KB learning where things are has less context left for the code it
 * came here to write, and prose grows by itself unless something says no.
 */
const BUDGETS = {
  'AGENTS.md': 2_560,
  'agents/llms.txt': 2_560,
  'agents/index.md': 3_584,
};

/**
 * Tier 2 files are per-component, so the budget is per file. Asserted here and
 * in the spec.
 *
 * The plan said 800, from the 626-byte median of a docs/component-specs.md
 * entry. That measured the wrong thing: an entry is prose bullets only, while a
 * rendered contract also carries ~250 bytes of frame (the do-not-edit header,
 * the folder line, the WCAG and APG references) plus a keyboard map and a
 * failure-mode list, neither of which a spec entry had. Written out, the roster
 * measured 0.8 KB to 1.5 KB, so 800 would have been met by deleting
 * `failureModes` -- the one field worth the most. This is the measured maximum
 * rounded up, which leaves the richest component room for about two more entries
 * and still makes a Tier 2 read cost roughly 450 tokens.
 */
export const TIER_2_BUDGET = 1_800;

