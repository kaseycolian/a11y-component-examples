/**
 * Render everything into a Map of repo-relative path -> contents.
 *
 * Order matters: the Tier 0 files quote the measured size of the Tier 1 files,
 * so those have to exist first. Nothing measures a Tier 0 file, so there is no
 * cycle -- and AGENTS.md deliberately does not list its own size, which would
 * make one.
 */
async function plan() {
  const manifest = await buildManifest();
  const rendered = new Map();

  rendered.set('agents/index.md', renderIndex(manifest));
  rendered.set('agents/index.json', renderIndexJson(manifest));
  for (const component of manifest.components) {
    if (!component.contract) continue;
    rendered.set(`agents/components/${component.slug}.md`, renderComponent(component, manifest));
  }

  rendered.set('AGENTS.md', renderAgentsMd(manifest, rendered));
  rendered.set('agents/llms.txt', renderLlmsTxt(manifest, rendered));

  return { manifest, rendered };
}

const bytes = (text) => Buffer.byteLength(text, 'utf8');

/** Every path the generator owns, so a leftover file counts as drift. */
async function ownedOnDisk() {
  const owned = new Set();
  if (existsSync(resolve(root, 'AGENTS.md'))) owned.add('AGENTS.md');

  const walk = async (rel) => {
    const dir = resolve(root, rel);
    if (!existsSync(dir)) return;
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const child = posix.join(rel, entry.name);
      if (entry.isDirectory()) await walk(child);
      else owned.add(child);
    }
  };
  await walk('agents');
  return owned;
}

function budgetProblems(rendered) {
  const problems = [];
  for (const [path, limit] of Object.entries(BUDGETS)) {
    const size = bytes(rendered.get(path) ?? '');
    if (size > limit) {
      problems.push(`${path} is ${kb(size)}, over its ${kb(limit)} budget by ${size - limit} bytes`);
    }
  }
  for (const [path, text] of rendered) {
    if (!path.startsWith('agents/components/')) continue;
    const size = bytes(text);
    if (size > TIER_2_BUDGET) {
      problems.push(`${path} is ${size} bytes, over the ${TIER_2_BUDGET}-byte Tier 2 budget`);
    }
  }
  return problems;
}

async function main() {
  const check = process.argv.includes('--check');
  const { rendered } = await plan();

  // `--print <path>` dumps one surface without writing anything, and runs
  // before the budget check so an over-budget file can still be inspected --
  // which is the moment you most need to see it.
  const printIdx = process.argv.indexOf('--print');
  if (printIdx !== -1) {
    const path = process.argv[printIdx + 1];
    if (!rendered.has(path)) {
      throw new Error(`--print: no surface "${path}". Have: ${[...rendered.keys()].join(', ')}`);
    }
    process.stdout.write(rendered.get(path));
    return;
  }

  const overBudget = budgetProblems(rendered);
  if (overBudget.length) {
    console.error('build-agent-surfaces: over budget');
    for (const problem of overBudget) console.error(`  ${problem}`);
    console.error('  Cut prose (docs/agents/preamble.md) rather than raising the budget.');
    process.exit(1);
  }

  const onDisk = await ownedOnDisk();
  const drift = [];
  for (const [path, text] of rendered) {
    const file = resolve(root, path);
    // Read raw rather than through readSource(): a generated file that somehow
    // acquired mojibake is drift, and reporting it as stale points at the fix.
    const current = existsSync(file) ? (await readFile(file, 'utf8')).replace(/^﻿/, '') : null;
    if (current !== text) drift.push(current === null ? `missing  ${path}` : `stale    ${path}`);
  }
  for (const path of onDisk) {
    if (!rendered.has(path)) drift.push(`orphan   ${path}`);
  }

  if (check) {
    if (drift.length) {
      console.error('build-agent-surfaces: the agent surfaces do not match their sources');
      for (const line of drift) console.error(`  ${line}`);
      console.error('  Run `npm run agents` and commit the result.');
      process.exit(1);
    }
    console.log(`build-agent-surfaces: ${rendered.size} surfaces match their sources`);
    return;
  }

  // Rebuild agents/ from scratch so a renamed or deleted component cannot leave
  // a file behind that still looks authoritative.
  await rm(resolve(root, 'agents'), { recursive: true, force: true });
  for (const [path, text] of rendered) {
    const file = resolve(root, path);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, text, 'utf8');
  }

  for (const [path, text] of rendered) {
    const limit = BUDGETS[path] ?? (path.startsWith('agents/components/') ? TIER_2_BUDGET : null);
    const room = limit ? `  (budget ${kb(limit)})` : '';
    console.log(`  ${kb(bytes(text)).padStart(8)}  ${path}${room}`);
  }
  console.log(`build-agent-surfaces: wrote ${rendered.size} surfaces`);
}

/**
 * Only run when invoked as a command.
 *
 * `tests/shared/agent-surfaces.spec.mjs` imports TIER_2_BUDGET from here so the
 * budget is stated once. Without this guard that import *executes* the script --
 * in write mode, since a Playwright worker's argv has no `--check` -- so several
 * workers raced each other rewriting agents/, and the loser exited 1 and took
 * its whole worker down. A module that does work when you import it is a trap
 * whoever imports it next will also fall into.
 */
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    await main();
  } catch (err) {
    console.error(`build-agent-surfaces: ${err.message}`);
    process.exit(1);
  }
}
